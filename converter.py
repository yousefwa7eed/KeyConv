# converter.py — جدول التحويل بين اللوحتين العربية والإنجليزية
# مسؤولية واحدة فقط: الخريطة + دالة تحويل النص حسب الأغلبية.
# لا يحتوي أي منطق Hook أو حارس أو Buffer — لضمان قابلية الاختبار والحفظ.
#
# الجدول مأخوذ من تخطيط "العربية (101)" في ويندوز نفسه (ToUnicodeEx)، لا من تخمين:
#   * الحرف الصغير -> الحرف العربي على نفس الزر بلا Shift
#   * الحرف الكبير -> ناتج نفس الزر مع Shift (الهمزات والتشكيل ولام-ألف الممدودة)
#   * "b" ينتج "لا" حرفين حقيقيين (لا صيغة عرض U+FEFB) فيظهر صحيحاً داخل الكلمة
# النتيجة: ما تكتبه في تخطيط يظهر كما كان سيظهر في التخطيط الآخر بنفس الأزرار.

# مفتاح (QWERTY) بلا Shift -> الحرف العربي على نفس الزر
_EN_UNSHIFTED = {
    "q": "ض", "w": "ص", "e": "ث", "r": "ق", "t": "ف",
    "y": "غ", "u": "ع", "i": "ه", "o": "خ", "p": "ح",
    "[": "ج", "]": "د",
    "a": "ش", "s": "س", "d": "ي", "f": "ب", "g": "ل",
    "h": "ا", "j": "ت", "k": "ن", "l": "م", ";": "ك", "'": "ط",
    "z": "ئ", "x": "ء", "c": "ؤ", "v": "ر", "b": "لا",
    "n": "ى", "m": "ة", ",": "و", ".": "ز", "/": "ظ",
    "`": "ذ",
}

# نفس الأزرار مع Shift: مهم لأن أ/إ/آ/لأ/لإ/لآ لا تُكتب في العربية إلا بـ Shift
_EN_SHIFTED = {
    "Q": "َ", "W": "ً", "E": "ُ", "R": "ٌ",          # حركات
    "T": "لإ", "Y": "إ", "U": "ِ", "I": "ٍ",
    "A": "ِ", "S": "ٍ", "G": "لأ", "H": "أ",
    "J": "ـ",                                         # تطويل
    "X": "ْ", "B": "لآ", "N": "آ",
    "~": "ّ",                                         # شدة
}

# ما ينتج حروفاً لاتينية/رموزاً عند التحويل لا يُضاف هنا إطلاقاً
# (مثل Shift+C -> "}" أو Shift+D -> "]"): تلك ليست حروفاً عربية.

# الحروف الكبيرة التي لا ينتج زرها المشترك حرفاً عربياً (مثل Shift+C -> "}")
# تعود إلى حرف الزر نفسه بلا Shift، وإلا بقيت لاتينية داخل النص المحوَّل.
_UPPER_FALLBACK = {
    lower.upper(): ar
    for lower, ar in _EN_UNSHIFTED.items()
    if len(lower) == 1 and lower.isalpha()
}

EN_TO_AR = {**_UPPER_FALLBACK, **_EN_UNSHIFTED, **_EN_SHIFTED}

# استثناءات اتجاه العربية -> الإنجليزية: ما يتوقعه المستخدم لا ما يقوله الزر حرفياً
_AR_OVERRIDES = {
    "،": ",", "؛": ";", "؟": "?", "٪": "%",          # ترقيم عربي -> ASCII
    "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",   # أرقام عربية-هندية (نص ملصق)
    "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
    "\ufefb": "b",                                     # صيغة العرض "لا" -> مفتاح b
}


def _build_ar_to_en():
    """معكوس الجدول: حرف واحد فقط، والأولوية للحروف غير المزاحة عند التكرار.

    بعض الأزرار تنتج نفس الحرف (A و U كلاهما كسرة)، فنحتفظ بأول مفتاح فقط.
    """
    table = dict(_AR_OVERRIDES)
    # الأولوية للحروف بلا Shift (مفاتيح صغيرة) ثم المزاحة
    for source in (_EN_UNSHIFTED, _EN_SHIFTED):
        for en, ar in source.items():
            if len(ar) == 1:
                table.setdefault(ar, en)
    return table


AR_TO_EN = _build_ar_to_en()


def _script_counts(text):
    """يعدّ الحروف القابلة للتحويل في النص: (عدد العربية، عدد الإنجليزية)."""
    ar_count = sum(1 for ch in text if ch in AR_TO_EN)
    en_count = sum(1 for ch in text if ch in EN_TO_AR)
    return ar_count, en_count


def detect_language(text):
    """لغة النص الغالبة: 'ar' أو 'en'، أو None عند التعادل/غياب الحروف.

    نستخدم نفس معيار convert_text (أغلبية الحروف القابلة للتحويل) حتى تكون
    لغة لوحة المفاتيح المطلوبة هي نفسها لغة النتيجة بلا تخمين مختلف.
    """
    ar_count, en_count = _script_counts(text or "")
    if ar_count == en_count:
        return None
    return "ar" if ar_count > en_count else "en"


def convert_text(text):
    """يحوّل نصاً بين العربية والإنجليزية حسب الأغلبية.

    - أغلبية عربية        -> إلى الإنجليزية (حرفاً بحرف على نفس المفتاح)
    - أغلبية إنجليزية     -> إلى العربية
    - تعادل 50/50         -> لا تحويل، يعيد النص كما هو
    - الحروف خارج الجدول  -> تمر كما هي دون تغيير
    """
    if not text:
        return text
    ar_count, en_count = _script_counts(text)
    if ar_count == 0 and en_count == 0:
        return text
    if ar_count == en_count:
        return text
    table = AR_TO_EN if ar_count > en_count else EN_TO_AR
    return "".join(table.get(ch, ch) for ch in text)
